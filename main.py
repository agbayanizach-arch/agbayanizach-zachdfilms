# 3. SLASH COMMAND: /restock <file>
# ==========================================
@bot.tree.command(name="restock", description="Restock accounts via a .txt file (Format: email:pass)")
@app_commands.describe(file="Upload the accounts text file")
@app_commands.checks.has_permissions(administrator=True)
async def restock_slash(interaction: discord.Interaction, file: discord.Attachment):
    """
    Slash Command Usage: /restock [file]
    Requires Administrator permission.
    """
    await interaction.response.defer(ephemeral=True)

    if not file.filename.endswith(".txt"):
        await interaction.followup.send("❌ Invalid file format! Please upload a clean `.txt` file.", ephemeral=True)
        return

    try:
        file_bytes = await file.read()
        content = file_bytes.decode("utf-8")
        lines = [line.strip() for line in content.splitlines() if line.strip()]
        
        added_count = 0
        for line in lines:
            if ":" in line:
                account_stock.append(line)
                added_count += 1

        await interaction.followup.send(f"✅ Successfully stocked **{added_count}** accounts! Total system inventory size: **{len(account_stock)}**.", ephemeral=True)
    except Exception as e:
        print(f"Restock error: {e}")
        await interaction.followup.send("❌ An unexpected error occurred while parsing the text file.", ephemeral=True)


# Error handler for slash command permissions
@restock_slash.error
async def restock_slash_error(interaction: discord.Interaction, error: app_commands.AppCommandError):
    if isinstance(error, app_commands.MissingPermissions):
        if not interaction.response.is_done():
            await interaction.response.send_message("❌ Access Denied! This command requires **Administrator** permissions.", ephemeral=True)
        else:
            await interaction.followup.send("❌ Access Denied! This command requires **Administrator** permissions.", ephemeral=True)


